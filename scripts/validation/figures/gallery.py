"""Gallery page generator: ``docs/validation/gallery.md`` keyed by physics tag.

Figures live at ``<root>/figures/<physics tag>/tier<N>/<figure_id>.png``, each
with the JSON sidecar written by :func:`core.save`. The page has:

1. an index table, one row per planned figure and one column per physics tag,
   so the same figure can be compared across versions (pending figures are
   listed, so the gaps are visible);
2. one section per physics tag (newest first), one subsection per tier, each
   figure with its caption, configuration hash, source test and headline
   metrics.

Plain Markdown with relative image links, so it renders on GitHub.
"""

from __future__ import annotations

import json
from pathlib import Path

PLAN_TIERS = {
    0: "Tier 0: mathematical checks",
    1: "Tier 1: components against FLEXPART",
    2: "Tier 2: the whole model against FLEXPART and NAME",
    3: "Tier 3: tracer experiments",
    4: "Tier 4: an inversion",
}


def _registry() -> dict[int, list]:
    from . import tier0

    return {0: tier0.FIGURES}


def collect(root: Path) -> dict[str, dict[int, list[dict]]]:
    """{physics tag: {tier: [sidecar dicts]}} from the figure tree under ``root``."""
    out: dict[str, dict[int, list[dict]]] = {}
    for side in sorted((root / "figures").glob("*/tier*/*.json")):
        meta = json.loads(side.read_text())
        meta["_path"] = side.with_suffix(".png").relative_to(root).as_posix()
        tag = side.parent.parent.name
        out.setdefault(tag, {}).setdefault(int(meta["tier"]), []).append(meta)
    return out


def _tag_order(found: dict[str, dict]) -> list[str]:
    """Newest first, by the most recent figure creation time under each tag."""

    def newest(tag: str) -> str:
        return max(m.get("created", "") for ms in found[tag].values() for m in ms)

    return sorted(found, key=newest, reverse=True)


def _fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.4g}"
    if isinstance(v, list):
        return ", ".join(_fmt(x) for x in v)
    return str(v)


def render(root: Path) -> str:
    found = collect(root)
    tags = _tag_order(found)
    reg = _registry()
    lines = [
        "# Validation figure gallery",
        "",
        "Generated by `scripts/validation/figures` (see "
        "[validation-plan.md §5–6](../validation-plan.md#5-the-figure-set)); do not edit by "
        "hand. Regenerate every figure and this page with:",
        "",
        "```",
        ".venv/bin/python scripts/validation/figures/make_all.py",
        "```",
        "",
        "Each figure title carries the physics tag and a hash of the exact configuration; "
        "the configuration itself is in the JSON file beside each image. Differences are "
        "shown as log₁₀ ratios, and bands are particle noise at ±2 standard errors from "
        "10 disjoint particle subsets.",
        "",
        "## Index",
        "",
    ]
    if not tags:
        lines += ["No figures have been generated yet.", ""]
    head = "| tier | figure | " + " | ".join(f"`{t}`" for t in tags) + " |"
    lines += [head, "|" + " --- |" * (2 + len(tags))]
    for tier, specs in reg.items():
        for spec in specs:
            cells = []
            for t in tags:
                hit = [m for m in found[t].get(tier, []) if m["figure_id"] == spec.figure_id]
                if hit:
                    cells.append(f"[figure](#{_anchor(t, spec.figure_id)})")
                elif spec.status != "ready":
                    cells.append(spec.status.split(":")[0])
                else:
                    cells.append("—")
            lines.append(f"| {tier} | {spec.title} | " + " | ".join(cells) + " |")
    pending = [(tier, s) for tier, ss in reg.items() for s in ss if s.status != "ready"]
    if pending:
        lines += ["", "Pending:"]
        lines += [f"- Tier {tier}, {s.title}: {s.status.split(': ', 1)[-1]}" for tier, s in pending]
    lines.append("")

    for tag in tags:
        lines += [f"## Physics `{tag}`", ""]
        for tier in sorted(found[tag]):
            lines += [f"### {PLAN_TIERS.get(tier, f'Tier {tier}')}", ""]
            order = {s.figure_id: i for i, s in enumerate(reg.get(tier, []))}
            for m in sorted(found[tag][tier], key=lambda m: order.get(m["figure_id"], 99)):
                lines += [
                    f'<a id="{_anchor(tag, m["figure_id"])}"></a>',
                    "",
                    f"#### {m['title']}",
                    "",
                    f"![{m['title']}]({m['_path']})",
                    "",
                    m["caption"],
                    "",
                    f"- config `{m['config_hash']}`, git `{m['git_rev'][:10]}`, "
                    f"created {m['created']}",
                ]
                if m.get("source"):
                    lines.append(f"- draws: `{m['source']}`")
                if m.get("metrics"):
                    lines.append(
                        "- metrics: "
                        + "; ".join(f"{k} = {_fmt(v)}" for k, v in m["metrics"].items())
                    )
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _anchor(tag: str, fid: str) -> str:
    return f"{tag}-{fid}".lower().replace("+", "-").replace(".", "-")


def write(root: Path) -> Path:
    path = root / "gallery.md"
    path.write_text(render(root))
    return path
